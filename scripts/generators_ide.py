def _rgba8(hex_color: str, alpha: str = "ff") -> str:
    """Normalize #RRGGBB or #RRGGBBAA into #RRGGBBAA for Zed v0.2.0 schema."""
    h = hex_color.lstrip("#").lower()
    if len(h) == 6:
        return f"#{h}{alpha}"
    if len(h) == 8:
        return f"#{h}"
    raise ValueError(f"Expected 6 or 8 hex digits, got: {hex_color}")


